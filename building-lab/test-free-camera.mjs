import assert from "node:assert/strict";
import {FreeCamera,normalizedStick} from "./free-camera.js";

const camera={
  position:{x:0,y:8,z:30,set(x,y,z){this.x=x;this.y=y;this.z=z;}},
  rotation:{order:"XYZ",set(x,y,z,order){this.x=x;this.y=y;this.z=z;this.order=order;}}
};
const free=new FreeCamera(camera,{speed:10,sprint:2.4,sensitivity:.003});
free.start({x:0,y:8,z:0});
assert.ok(free.active);
assert.equal(camera.rotation.order,"YXZ");
assert.ok(Math.abs(free.yaw)<1e-9,"camera initially looks toward -Z");
assert.ok(Math.abs(free.pitch)<1e-9);
free.setStick(0,1);
free.update(.05);
assert.ok(Math.abs(camera.position.z-29.5)<1e-8,"forward moves down -Z");
free.setStick(1,0);
free.update(.05);
assert.ok(Math.abs(camera.position.x-.5)<1e-8,"strafe moves along +X");
free.setStick(0,0);
free.setVertical(1);
free.update(.05);
assert.ok(Math.abs(camera.position.y-8.5)<1e-8,"fly upwards on Y");
free.setVertical(-1);
free.update(.05);
assert.ok(Math.abs(camera.position.y-8)<1e-8,"fly downwards on Y");
free.setVertical(0);
free.look(-Math.PI/2/.003,0);
assert.ok(Math.abs(free.yaw-Math.PI/2)<1e-8);
free.setStick(0,1);
const before=camera.position.x;
free.update(.05);
assert.ok(camera.position.x<before-.49,"turning changes forward to -X");
free.look(0,-99999);
assert.ok(free.pitch<=1.49&&free.pitch>=-1.49,"pitch clamped");
const point=free.targetAt();
assert.ok(Number.isFinite(point.x+point.y+point.z));
free.keys.add("KeyE");
free.setStick(0,0);
const oldY=camera.position.y;
free.update(.05);
assert.ok(camera.position.y>oldY,"E moves upwards");
free.keys.delete("KeyE");
free.boost=true;
free.setStick(1,0);
const oldX=camera.position.x,oldZ=camera.position.z;
free.update(.05);
assert.ok(Math.hypot(camera.position.x-oldX,camera.position.z-oldZ)>1.19,"boost makes movement faster in local direction");
free.stop();
const stopX=camera.position.x;
free.update(.05);
assert.equal(camera.position.x,stopX,"stopped camera does not move");
assert.equal(free.axisY,0);
assert.equal(free.axisX,0);
free.start({x:0,y:8,z:0});
assert.equal(free.keys.size,0,"keys clear after toggle");
free.camera.position.set(260,114.9,260);
free.setStick(1,0);
free.setVertical(1);
free.update(10);
assert.ok(camera.position.y<=115&&Math.abs(camera.position.x)<=260);
const rect={left:0,top:0,width:140,height:140};
const center=normalizedStick(70,70,rect);
assert.deepEqual(center,{x:0,z:0});
const up=normalizedStick(70,-500,rect);
assert.ok(up.z>0.99,"up drag moves forward");
const right=normalizedStick(400,70,rect);
assert.ok(right.x>.99,"right drag strafes right");
const diagonal=normalizedStick(400,-400,rect);
assert.ok(Math.hypot(diagonal.x,diagonal.z)<=1.0000001);
console.log("Free camera 3.1.1: XYZ, yaw/pitch, speed, keys, bounds, release, stick PASS");
